/**
 * Post-build: prepare dist/ for Cloudflare Pages deployment.
 *
 * The @astrojs/cloudflare adapter generates:
 *   dist/client/   — static assets (web root)
 *   dist/server/   — Worker code (entry.mjs + chunks)
 *   .wrangler/deploy/config.json — redirects Pages CI to dist/server/wrangler.json
 *
 * That redirect config carries Workers-only fields (main, rules, assets) that
 * Cloudflare Pages CI's stricter wrangler validation now rejects.
 *
 * Fix strategy:
 *   1. Move dist/client/ contents to dist/   — align the web root with where Pages
 *      expects static files when using _worker.js convention.
 *   2. Create dist/_worker.js               — Pages auto-detects this as the SSR Worker.
 *      It re-exports from server/entry.mjs; Pages resolves ESM imports natively.
 *   3. Delete .wrangler/deploy/config.json  — stop the broken redirect.
 *
 * Result: Pages serves static files from dist/ and routes SSR/API requests through
 * _worker.js → server/entry.mjs, with env.ASSETS pointing at the correct web root.
 *
 * Remove this script once @astrojs/cloudflare ships a fix.
 */

import {
  readFileSync, writeFileSync, unlinkSync, existsSync,
  readdirSync, mkdirSync, renameSync, statSync, rmSync,
} from "fs";
import { resolve, join, dirname } from "path";
import { fileURLToPath } from "url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const dist = resolve(root, "dist");
const clientDir = join(dist, "client");

// 1. Move dist/client/ contents up to dist/
if (existsSync(clientDir)) {
  const moveDir = (src, dest) => {
    for (const entry of readdirSync(src)) {
      const srcPath = join(src, entry);
      const destPath = join(dest, entry);
      const stat = statSync(srcPath);
      if (stat.isDirectory()) {
        mkdirSync(destPath, { recursive: true });
        moveDir(srcPath, destPath);
        rmSync(srcPath, { recursive: true, force: true });
      } else {
        renameSync(srcPath, destPath);
      }
    }
  };
  moveDir(clientDir, dist);
  rmSync(clientDir, { recursive: true, force: true });
  console.log("fix-deploy-config: moved dist/client/ → dist/");
} else {
  console.log("fix-deploy-config: dist/client/ not found, skipping move.");
}

// 2. Create dist/_worker.js — Cloudflare Pages serves this as the Worker entry.
//    server/entry.mjs uses relative ESM imports for its chunks; Pages resolves
//    these natively from the deployment bundle without bundling.
writeFileSync(
  join(dist, "_worker.js"),
  `// Auto-generated by scripts/fix-deploy-config.mjs\nexport { default } from './server/entry.mjs';\n`,
  "utf8"
);
console.log("fix-deploy-config: created dist/_worker.js.");

// 3. Delete the deploy redirect config so Pages CI uses wrangler.jsonc directly.
const deployConfig = resolve(root, ".wrangler/deploy/config.json");
if (existsSync(deployConfig)) {
  unlinkSync(deployConfig);
  console.log("fix-deploy-config: deleted .wrangler/deploy/config.json (redirect removed).");
}
