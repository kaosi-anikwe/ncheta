/**
 * Post-build: prepare dist/ for Cloudflare Pages deployment.
 *
 * The @astrojs/cloudflare adapter generates:
 *   dist/server/wrangler.json  — a Workers config with `main`, `rules`, `assets`
 *   .wrangler/deploy/config.json — redirects Pages CI to use the above config
 *
 * Cloudflare Pages CI now rejects Workers-only fields (`main`, `rules`, `assets`)
 * when validating a Pages deployment config, so the redirect mechanism breaks.
 *
 * Fix:
 *   1. Delete .wrangler/deploy/config.json  — stop the redirect.
 *   2. Create dist/_worker.js               — Pages auto-detects this as the Worker
 *      entry point. It re-exports from dist/server/entry.mjs which is a pre-compiled
 *      ESM module; Pages supports relative ESM imports natively, no bundling needed.
 *   3. Remove KV entries without "id"       — belt-and-suspenders cleanup.
 *
 * Remove this script (and the postinstall entry in package.json) once
 * @astrojs/cloudflare ships a fix.
 */

import { readFileSync, writeFileSync, unlinkSync, existsSync } from "fs";
import { resolve, dirname } from "path";
import { fileURLToPath } from "url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

// 1. Delete the deploy redirect config so Pages uses wrangler.jsonc directly.
const deployConfig = resolve(root, ".wrangler/deploy/config.json");
if (existsSync(deployConfig)) {
  unlinkSync(deployConfig);
  console.log("fix-deploy-config: deleted .wrangler/deploy/config.json (redirect removed).");
} else {
  console.log("fix-deploy-config: .wrangler/deploy/config.json not found, skipping.");
}

// 2. Create dist/_worker.js — Cloudflare Pages serves this as the Worker entry.
//    It re-exports from server/entry.mjs, which uses relative ESM imports for
//    its chunks; Pages resolves those natively without bundling.
const workerJs = resolve(root, "dist/_worker.js");
writeFileSync(
  workerJs,
  `// Auto-generated by scripts/fix-deploy-config.mjs\nexport { default } from './server/entry.mjs';\n`,
  "utf8"
);
console.log("fix-deploy-config: created dist/_worker.js.");

// 3. Belt-and-suspenders: remove any KV namespaces without an id from the
//    server wrangler.json (even though we no longer use it for deployment).
const serverConfig = resolve(root, "dist/server/wrangler.json");
if (existsSync(serverConfig)) {
  const config = JSON.parse(readFileSync(serverConfig, "utf8"));
  const removed = [];

  if (Array.isArray(config.kv_namespaces)) {
    config.kv_namespaces = config.kv_namespaces.filter((kv) => {
      if (!kv.id) { removed.push(kv.binding); return false; }
      return true;
    });
    if (config.kv_namespaces.length === 0) delete config.kv_namespaces;
  }
  if (config.previews?.kv_namespaces) {
    config.previews.kv_namespaces = config.previews.kv_namespaces.filter((kv) => kv.id);
    if (config.previews.kv_namespaces.length === 0) delete config.previews.kv_namespaces;
  }

  if (removed.length > 0) {
    writeFileSync(serverConfig, JSON.stringify(config), "utf8");
    console.log(`fix-deploy-config: removed KV namespace(s) without id: ${removed.join(", ")}`);
  }
}
